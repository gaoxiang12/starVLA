#!/usr/bin/env bash
set -euo pipefail

# From-scratch 4x4 DINOv3 baseline with the WALA-style transition teacher and
# action-query student trained jointly in one 200k-step run.

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"

env \
  RUN_ID="${RUN_ID:-lewm_oft_libero_dinov3b_spatial4x4_wala_combined_sigreg0_trainenc1e6_statecond_200k}" \
  STEPS="${STEPS:-200000}" \
  SAVE_INTERVAL="${SAVE_INTERVAL:-10000}" \
  WARMUP="${WARMUP:-2000}" \
  BATCH="${BATCH:-8}" \
  VISUAL_TOKENS_PER_VIEW=16 \
  VISUAL_TOKEN_DIM=384 \
  VISUAL_DIAGNOSTICS=true \
  USE_DENSE_PATCH_ACTION=false \
  TRAIN_ENCODER=true \
  LATENT_WEIGHT=1.0 \
  TOKEN_DIVERSITY_WEIGHT=0.02 \
  TOKEN_VARIANCE_WEIGHT=0.02 \
  RESIDUAL_SIGREG_WEIGHT=0.0 \
  TRANSITION_MODE=combined \
  TRANSITION_HIDDEN_DIM=384 \
  TRANSITION_NUM_TOKENS=8 \
  TRANSITION_ENCODER_DEPTH=2 \
  TRANSITION_DECODER_DEPTH=2 \
  TRANSITION_RESAMPLER_DEPTH=2 \
  TRANSITION_HEADS=6 \
  TRANSITION_TEACHER_WEIGHT=1.0 \
  TRANSITION_ALIGNMENT_WEIGHT=0.005 \
  TRANSITION_DECODE_WEIGHT=0.05 \
  TRANSITION_COSINE_WEIGHT=0.1 \
  TRANSITION_ALIGNMENT_L1_WEIGHT=0.1 \
  TRANSITION_DETACH_ACTION_QUERIES=false \
  TRANSITION_JOINT_FREEZE_BASE=false \
  BASE_LR="${BASE_LR:-1e-4}" \
  ACTION_LR="${ACTION_LR:-1e-4}" \
  ENCODER_LR="${ENCODER_LR:-1e-6}" \
  USE_STATE_COND=true \
  INCLUDE_STATE=true \
  LATENT_STATS_MOMENTUM=0.99 \
  PRETRAINED_CKPT= \
  WANDB_MODE="${WANDB_MODE:-disabled}" \
  "$@" \
  bash "${SCRIPT_DIR}/run_lewm_oft_dinov3_200k_train_eval.sh"
